/**
 * Іздеуге арналған әріп бүктеу.
 *
 * Мәселе: оқушы «Тауке хан» деп іздейді, ал кітапта «Тәуке хан» деп жазылған.
 * Қазақ әліпбиінің тоғыз әрпі орыс әліпбиіндегі ұқсасына жақын тұр, ал оқушы
 * (әсіресе телефоннан) оларды жиі алмастырып жазады. Сол себепті сөзді
 * салыстырар алдында екі жағын да «бүктеп» аламыз: ә мен а бір әріпке
 * айналады да, екеуі де табылады.
 *
 * Бұл емле мәселесі, мағына мәселесі емес — сондықтан мұнда векторлық іздеу
 * қажет емес әрі одан нашар жұмыс істер еді: «Тәуке хан» деген нақты атауды
 * ұқсас мағыналы басқа мәтінмен шатастырып алуы мүмкін.
 *
 * Postgres жағында дәл осы ауыстыру `translate()` арқылы жасалады — қосымша
 * кеңейтім орнатудың қажеті жоқ.
 */

/** Қазақ әріптері және олардың бүктелген түрі. Екі жол бірдей ұзындықта болуы керек. */
export const FOLD_FROM = "әөүұқғіңһ";
export const FOLD_TO = "аоуукгинх";

const FOLD_MAP = new Map<string, string>(
  [...FOLD_FROM].map((char, index) => [char, FOLD_TO[index]])
);

/**
 * Мәтінді салыстыруға дайындайды: кіші әріпке түсіріп, қазақ әріптерін
 * бүктейді. Басқа таңбаларға тиіспейді.
 */
export function foldKazakh(text: string): string {
  return [...text.toLowerCase()].map((char) => FOLD_MAP.get(char) ?? char).join("");
}

/**
 * Сұрауды сөздерге бөледі.
 *
 * Әр сөз бөлек ізделеді де, бәрі табылуы талап етіледі — сонда сөздердің
 * реті маңызды болмайды («хан Тәуке» де «Тәуке хан» да табылады).
 */
export function splitSearchWords(term: string, limit = 6): string[] {
  return foldKazakh(term)
    .split(/[^\p{L}\p{N}]+/u)
    .map((word) => word.trim())
    .filter((word) => word.length >= 2)
    .slice(0, limit);
}

/** Postgres `ILIKE` үшін арнайы таңбаларды қорғау */
export function escapeLikePattern(value: string): string {
  return value.replace(/[\\%_]/g, (char) => `\\${char}`);
}
